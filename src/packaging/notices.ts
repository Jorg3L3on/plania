// PLA-I2-17: THIRD_PARTY_NOTICES, generated from the licences of the production dependencies (what ships in a
// release package and in the built screen). `pnpm notices` writes it; `pnpm release:pack` writes a fresh one into
// the package. Dev dependencies (build and test tools) never ship and are left out.
//
// It walks node_modules the way Node resolves a package (the package's own node_modules, then each parent's), so it
// reads pnpm's layout and a flat one alike. Packages that only hold one platform's binary (an `os` or `cpu` field,
// such as @node-rs/argon2-darwin-arm64) are left out so the file is the same on every machine; their parent package,
// which is listed, carries the same licence.
import { existsSync, readdirSync, readFileSync, realpathSync } from "node:fs";
import path from "node:path";

export type Notice = { name: string; version: string; license: string; text: string | null; homepage: string | null };

type Pkg = {
  name?: string;
  version?: string;
  license?: string | { type?: string };
  licenses?: Array<{ type?: string }>;
  homepage?: string;
  repository?: string | { url?: string };
  dependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
  os?: string[];
  cpu?: string[];
};

const readPkg = (dir: string): Pkg | null => {
  try {
    return JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8")) as Pkg;
  } catch {
    return null;
  }
};

// Where `name` resolves from a package at `fromDir`: its own node_modules, then every ancestor's.
export function resolveDep(fromDir: string, name: string): string | null {
  let dir = fromDir;
  for (;;) {
    const candidate = path.join(dir, "node_modules", name);
    if (existsSync(path.join(candidate, "package.json"))) return realpathSync(candidate);
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

function licenseText(dir: string): string | null {
  let files: string[];
  try {
    files = readdirSync(dir);
  } catch {
    return null;
  }
  const found = files.filter((f) => LICENSE_FILE.test(f) || /^licen[cs]e[-.]/i.test(f)).sort();
  if (found.length === 0) return null;
  return found.map((f) => readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n").trim()).join("\n\n");
}

function licenseName(p: Pkg): string {
  if (typeof p.license === "string") return p.license;
  if (p.license && typeof p.license === "object" && p.license.type) return p.license.type;
  if (Array.isArray(p.licenses)) return p.licenses.map((l) => l.type).filter(Boolean).join(" OR ") || "UNKNOWN";
  return "UNKNOWN";
}

function homepage(p: Pkg): string | null {
  if (p.homepage) return p.homepage;
  const r = typeof p.repository === "string" ? p.repository : p.repository?.url;
  return r ? r.replace(/^git\+/, "").replace(/\.git$/, "") : null;
}

// Every package reachable from the root's `dependencies` (and the optional ones that are installed).
export function collectNotices(rootDir: string): Notice[] {
  const root = readPkg(rootDir);
  if (!root) throw new Error(`no package.json in ${rootDir}`);
  const seen = new Map<string, Notice>();
  const visited = new Set<string>();
  const queue: Array<{ from: string; name: string }> = Object.keys(root.dependencies ?? {}).map((name) => ({ from: rootDir, name }));
  while (queue.length > 0) {
    const { from, name } = queue.shift()!;
    const dir = resolveDep(from, name);
    if (!dir || visited.has(dir)) continue;
    visited.add(dir);
    const p = readPkg(dir);
    if (!p) continue;
    for (const dep of [...Object.keys(p.dependencies ?? {}), ...Object.keys(p.optionalDependencies ?? {})]) queue.push({ from: dir, name: dep });
    if (p.os || p.cpu) continue;
    const id = `${p.name ?? name}@${p.version ?? "0.0.0"}`;
    if (!seen.has(id)) seen.set(id, { name: p.name ?? name, version: p.version ?? "0.0.0", license: licenseName(p), text: licenseText(dir), homepage: homepage(p) });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

export function renderNotices(notices: Notice[]): string {
  const head = [
    "THIRD-PARTY SOFTWARE NOTICES",
    "",
    "Plania includes the following third-party software, used under the licences below.",
    "This file is generated by `pnpm notices` from the production dependencies; do not edit it by hand.",
    "",
    `${notices.length} packages.`,
  ];
  const blocks = notices.map((n) =>
    [
      "-".repeat(78),
      `${n.name} ${n.version}`,
      `License: ${n.license}`,
      ...(n.homepage ? [`Source: ${n.homepage}`] : []),
      "",
      n.text ?? `(No licence file in the package; its package.json declares ${n.license}.)`,
    ].join("\n"),
  );
  return [...head, "", ...blocks, ""].join("\n");
}
